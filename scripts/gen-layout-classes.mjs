// Writes src/components/layoutClasses.ts: literal Tailwind class strings for the layout
// primitives (Container, Stack, Grid). Tailwind only sees classes written out in full,
// so every spacing / column / span class per breakpoint is spelled out here.
import { writeFileSync } from "node:fs";
import { join, resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "src/components/layoutClasses.ts");

const variants = { base: "", m: "mobile:", t: "tablet:", l: "laptop:", d: "desktop:" };
const units = ["0", "1", "1.5", "2", "3", "4", "5", "6", "7", "8", "10", "12", "16"];
const cols = Array.from({ length: 12 }, (_, i) => String(i + 1));

const table = (make) =>
  Object.fromEntries(Object.entries(variants).map(([k, v]) => [k, Object.fromEntries(make(v))]));

const data = {
  gap: table((v) => units.map((u) => [u, `${v}gap-${u}`])),
  p: table((v) => units.map((u) => [u, `${v}p-${u}`])),
  px: table((v) => units.map((u) => [u, `${v}px-${u}`])),
  py: table((v) => units.map((u) => [u, `${v}py-${u}`])),
  cols: table((v) => cols.map((c) => [c, `${v}grid-cols-${c}`])),
  span: table((v) => [...cols.map((c) => [c, `${v}col-span-${c}`]), ["full", `${v}col-span-full`]]),
  direction: table((v) => [["row", `${v}flex-row`], ["column", `${v}flex-col`]]),
  display: table((v) => [["none", `${v}hidden`], ["contents", `${v}contents`]]),
};

const body = Object.entries(data)
  .map(([name, t]) => `  ${name}: ${JSON.stringify(t, null, 2).replace(/\n/g, "\n  ")},`)
  .join("\n");

writeFileSync(
  out,
  `// Generated by scripts/gen-layout-classes.mjs — do not edit by hand.\n` +
    `// Literal class strings so Tailwind can see every responsive layout class.\n\n` +
    `export const LAYOUT_CLASSES = {\n${body}\n} as const;\n`
);
console.log("gen-layout-classes: src/components/layoutClasses.ts");
